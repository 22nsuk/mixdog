export type PixelIconName = keyof typeof GRIDS;

const PATHS = Object.fromEntries(
  Object.entries(GRIDS).map(([name, rows]) => [
    name,
    rows.flatMap((row, y) => [...row].map((cell, x) => (cell === '#' ? `M${x} ${y}h1v1h-1z` : ''))).join(''),
  ])
) as Record<PixelIconName, string>;

export function PixelIcon({ name, size = 12 }: { name: PixelIconName; size?: number }) {
  return (
    <svg
      className="pixel-icon"
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden="true"
      data-icon={name}
    >
      <path fill="currentColor" d={PATHS[name]} />
    </svg>
  );
}
